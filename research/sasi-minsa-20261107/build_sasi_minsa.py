def add(y, p, q, sub, law, art, para, basis, conf, issue, cur=None):
    r = {
        'year': y, 'round': y - 1958, 'part': PART[p], 'q': q, 'sub': sub,
        'law': LAW.get(law, law), 'article': art, 'para': para,
        'basis': BASIS[basis], 'confidence': CONF[conf], 'issue': issue,
        'kind': '법률',
    }
