def check():
    """원문 폴더에 없는 법령을 '확실'로 적은 줄, 설문 목록과 어긋난 줄을 찾는다."""
    bad = [(r['year'], r['q'], r['sub'], r['law'], r['article']) for r in rows
           if r['basis'] != '문제지 발췌' and r['law'] not in IN_SOURCES and r['confidence'] == '확실']
    keys = set((r['year'], r['part'], r['q'], r['sub']) for r in rows if r['sub'] != '전체')
    allk = set((r['year'], r['part'], r['q'], r['sub']) for r in subqs)
    dup = sorted(k for k in allk if sum(1 for x in subqs if (x['year'], x['part'], x['q'], x['sub']) == k) > 1)
    return bad, sorted(keys - allk), sorted(allk - keys), dup


