def kind_of(law_name):
    if law_name == '헌법':
        return '헌법'
    if '조례' in law_name:
        return '자치법규'
    if law_name.endswith('시행령'):
        return '대통령령'
    if law_name.endswith('시행규칙') or law_name.endswith('계약사무규칙'):
        return '부령'
    if law_name in ('행정소송규칙', '민사소송규칙'):
        return '대법원규칙'
    if law_name.endswith('지침'):
        return '행정규칙'  # v0 공법 시범이 고시·훈령에 쓴 값
    return '법률'


def round_of(y):
    return y - 1984  # 2017 = 33회 ... 2026 = 42회


def add(y, p, q, sub, law, art, para, basis, conf, issue, kind=None, cur=None):
    law_name = LAW.get(law, law)
    r = {
        'year': y, 'round': round_of(y), 'part': PART[p], 'q': q, 'sub': sub,
        'law': law_name, 'article': art, 'para': para,
        'basis': BASIS[basis], 'confidence': CONF[conf], 'issue': issue,
        'kind': kind or kind_of(law_name),
    }
    if cur is not None:
        r['current'] = cur
    rows.append(r)


def b(y, p, q, sub, name, issue, basis='C', conf=None, cur=None):
    table = BUNDLE if name in BUNDLE else PUB
    for law, art, para, c in table[name]:
        BUNDLE_ROWS.append([len(rows), name])
        add(y, p, q, sub, law, art, para, basis, conf or c, issue, cur=cur)


def ex(y, p, q, law, arts, kind=None, sub='전체', issue='참조조문 발췌'):
    """문제지에 붙은 참조조문(현행 법령을 고쳐 붙인 것·가상 조문). 원장에서 빠진다."""
    for a in arts:
        add(y, p, q, sub, law, a, '', 'E', 'S', issue, kind=kind)


def pre(y, p, q, sub, law, cart, cpara, issue, note):
    """출제 당시 없던 조문으로 지금 답하는 줄(v0 사시 공법 꼴): article '', current = 현행 조문, 늘 확인 필요."""
