def kind_of(law_name):
    if law_name == '헌법':
        return '헌법'
    if law_name.endswith('시행령'):
        return '대통령령'
    if law_name.endswith('시행규칙') or law_name == '감정평가에 관한 규칙':
        return '부령'
    if law_name == '행정소송규칙':
        return '대법원규칙'
    if law_name == LAW['PJ']:
        return '행정규칙'
    return '법률'


def add(y, q, sub, law, art, para, basis, conf, issue, cur=None):
    law_name = LAW.get(law, law)
    r = {
        'year': y, 'round': y - 1989, 'part': PART, 'q': q, 'sub': sub,
        'law': law_name, 'article': art, 'para': para,
        'basis': BASIS[basis], 'confidence': CONF[conf], 'issue': issue,
        'kind': kind_of(law_name),
    }
    if cur is not None:
        r['current'] = cur
    rows.append(r)


def b(y, q, sub, name, issue, basis='C', conf=None):
    for law, art, para, c in BUNDLE[name]:
        BUNDLE_ROWS.append([len(rows), name])
        add(y, q, sub, law, art, para, basis, conf or c, issue)


def ex(y, q, sub, law, arts, issue='참조 조문 발췌', cur=None):
    """문제지 참조 조문. arts: [(조, 항)]. cur: {(조, 항): current}"""
    for art, para in arts:
        c = cur.get((art, para)) if cur else None
        add(y, q, sub, law, art, para, 'E', 'S', issue, cur=c)


def pre(y, q, sub, law, cart, cpara, issue, note):
    """출제 당시 조문 없음(또는 시행 전) -> 현행 조문에 댐. 항상 확인 필요."""
    law_name = LAW.get(law, law)
    rows.append({
        'year': y, 'round': y - 1989, 'part': PART, 'q': q, 'sub': sub,
        'law': law_name, 'article': '', 'para': '',
        'basis': BASIS['C'], 'confidence': CONF['U'], 'issue': issue,
        'kind': kind_of(law_name),
        'current': {'law': law_name, 'article': cart, 'para': cpara, 'note': '출제 당시 조문 없음. ' + note},
    })


def s(y, q, sub, qtype, pts):
    subqs.append({'year': y, 'round': y - 1989, 'part': PART, 'q': q, 'sub': sub,
                  'qtype': qtype, 'points': pts})


