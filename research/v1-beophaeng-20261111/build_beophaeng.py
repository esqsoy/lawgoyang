def kind_of(law_name):
    if law_name == '헌법':
        return '헌법'
    if '조례' in law_name:
        return '자치법규'
    if law_name.endswith('시행령'):
        return '대통령령'
    if law_name.endswith('시행규칙'):
        return '부령'
    if law_name in SCOURT_RULES:
        return '대법원규칙'
    return '법률'


def add(y, p, q, sub, law, art, para, basis, conf, issue, kind=None, cur=None):
    """cur: None | dict {law?, article, para, note} | '없음'."""
    law_name = LAW.get(law, law)
    if basis == 'C' and law_name not in LOCAL:
        conf = 'U'
    if cur is None and basis != 'E':
        if law_name == '행정기본법' and y <= 2020:
            cur = {'article': art, 'para': para, 'note': HG_NEW}
        elif law_name == '행정소송규칙' and y <= 2022:
            cur = {'article': art, 'para': para, 'note': HSR_NEW}
    r = {
        'year': y, 'round': y - 1982, 'part': PART[p], 'q': q, 'sub': sub,
        'law': law_name, 'article': art, 'para': para,
        'basis': BASIS[basis], 'confidence': CONF[conf], 'issue': issue,
        'kind': kind or kind_of(law_name),
    }
    if cur is not None:
        r['current'] = cur
    rows.append(r)


def b(y, p, q, sub, name, issue, basis='C', conf=None):
    """고정 묶음. conf를 주면 묶음 안 모든 줄의 확신도를 그것으로 바꾼다."""
    for law, art, para, c in (BUNDLE.get(name) or BUNDLE_G[name]):
        BUNDLE_ROWS.append([len(rows), name])
        add(y, p, q, sub, law, art, para, basis, conf or c, issue)


