"""Build mapping.jsonl for the 변호사시험 공법 사례형 pilot (1회 2012 ~ 15회 2026).

Usage: python3 -I build_mapping.py OUT.jsonl

Codes
  basis: M = 문제지 명시, C = Claude 판단, E = 문제지 발췌
  conf : S = 확실, U = 확인 필요
Every entry is one article (조, 항 if clear) that a model answer needs for that 설문.
Old 지방자치법 numbers (before the 2021 전부개정, 시행 2022. 1. 13.) carry
"current" = the article in the current law (Claude memory, 확인 필요).
"""
import json
import sys

LAW = {
    'H': '헌법', 'HJ': '헌법재판소법', 'HS': '행정소송법', 'HC': '행정절차법',
    'HG': '행정기본법', 'HSM': '행정심판법', 'GB': '국가배상법', 'JJ': '지방자치법',
    'TB': '공익사업을 위한 토지 등의 취득 및 보상에 관한 법률',
}
BASIS = {'M': '문제지 명시', 'C': 'Claude 판단', 'E': '문제지 발췌'}
CONF = {'S': '확실', 'U': '확인 필요'}

# old 지방자치법 article -> (current article, current para)
JJ_NOW = {
    ('9', '2'): ('13', '2'), ('14', ''): ('18', ''), ('15', '1'): ('19', '1'),
    ('16', '1'): ('21', '1'), ('17', '1'): ('22', '1'), ('17', '2'): ('22', '2'),
    ('22', ''): ('28', '1'), ('73', ''): ('85', ''), ('95', ''): ('108', ''),
    ('104', '4'): ('117', '4'), ('172', ''): ('192', ''),
}

rows = []


def add(rnd, q, sub, law, art, para, basis, conf, issue, kind=None, old_jj=False):
    law_name = LAW.get(law, law)
    if kind is None:
        if law_name == '헌법':
            kind = '헌법'
        elif '조례' in law_name:
            kind = '자치법규'
        elif law_name.endswith('시행령') or law_name == '행정권한의 위임 및 위탁에 관한 규정':
            kind = '대통령령'
        elif law_name.endswith('시행규칙') or law_name.endswith('기준에 관한 규칙'):
            kind = '부령'
        else:
            kind = '법률'
    r = {
        'year': 2011 + rnd, 'round': rnd, 'part': '공법', 'q': q, 'sub': sub,
        'law': law_name, 'article': art, 'para': para,
        'basis': BASIS[basis], 'confidence': CONF[conf], 'issue': issue,
        'kind': kind,
    }
    if old_jj:
        now = JJ_NOW[(art, para)]
        r['current'] = {'article': now[0], 'para': now[1],
                        'note': '2021 전부개정 전 조문번호. 현행 번호는 Claude 기억(확인 필요)'}
    rows.append(r)


def ex(rnd, q, law, arts, kind=None, sub='전체'):
    """문제지 발췌 조문 일괄 등록. arts: list of article strings."""
    for a in arts:
        add(rnd, q, sub, law, a, '', 'E', 'S', '참조조문 발췌', kind=kind)


