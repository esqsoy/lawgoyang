def kind_of(law_name):
    if law_name == '헌법':
        return '헌법'
    if law_name in ('행정소송규칙', '민사소송규칙'):
        return '대법원규칙'
    if law_name.endswith('시행령') or law_name.endswith('에 관한 규정'):
        return '대통령령'
    if law_name.endswith('시행규칙'):
        return '부령'
    return '법률'


def add(y, p, q, sub, law, art, para, basis, conf, issue, cur=None):
    law_name = LAW.get(law, law)
    r = {
        'year': y, 'round': y - 1991, 'part': PART[p], 'q': q, 'sub': sub,
        'law': law_name, 'article': art, 'para': para,
        'basis': BASIS[basis], 'confidence': CONF[conf], 'issue': issue,
        'kind': kind_of(law_name),
    }
    if cur is not None:
        r['current'] = cur
    rows.append(r)


def b(y, p, q, sub, name, issue, basis='C', conf=None, cur=None):
    for law, art, para, c in BUNDLE[name]:
        BUNDLE_ROWS.append([len(rows), name])
        add(y, p, q, sub, law, art, para, basis, conf or c, issue, cur)


def ex(y, p, q, sub, law, arts, conf='S', issue='참조조문 발췌'):
    """문제지 발췌 조문. arts: list of (article, para)."""
    for a, para in arts:
        add(y, p, q, sub, law, a, para, 'E', conf, issue)


def s(y, p, q, sub, qtype='사례', pts=''):
    subqs.append({'year': y, 'round': y - 1991, 'part': PART[p], 'q': q, 'sub': sub,
                  'qtype': qtype, 'points': pts})


