def summary():
    from collections import Counter, defaultdict
    out = []
    qt = Counter((x['part'], x['qtype']) for x in subqs)
    out.append('설문 %d (사례 %d, 이론 %d)' % (
        len(subqs), sum(1 for x in subqs if x['qtype'] == '사례'),
        sum(1 for x in subqs if x['qtype'] == '이론')))
    for p in PART.values():
        out.append('  %s: 사례 %d 이론 %d' % (p, qt[(p, '사례')], qt[(p, '이론')]))
    cf = Counter(r['confidence'] for r in rows if r['basis'] != '문제지 발췌')
    out.append('줄 %d: 확실 %d, 확인 필요 %d, 발췌 %d, 문제지 명시 %d' % (
        len(rows), cf['확실'], cf['확인 필요'],
        sum(1 for r in rows if r['basis'] == '문제지 발췌'),
        sum(1 for r in rows if r['basis'] == '문제지 명시')))
    by = defaultdict(lambda: Counter())
    for r in rows:
        by[(r['year'], r['part'])][r['confidence']] += 1
    qs = defaultdict(set)
    for r in rows:
        qs[r['year']].add((r['part'], r['q']))
    ns = Counter(x['year'] for x in subqs)
    for y in sorted(qs):
        cells = []
        for p in PART.values():
            c = by[(y, p)]
            cells.append('%s %d/%d' % (p[-4:], c['확실'], c['확인 필요']))
        out.append('%d: 문 %d, 설문 %d, 줄 %d | %s' % (
            y, len(qs[y]), ns[y], sum(1 for r in rows if r['year'] == y), ' | '.join(cells)))
    lc = Counter(r['law'] for r in rows)
    out.append('법령별: ' + ', '.join('%s %d' % kv for kv in lc.most_common()))
    out.append('묶음 줄 %d' % len(BUNDLE_ROWS))
    arts = set((r['law'], r['article']) for r in rows if r['basis'] != '문제지 발췌')
    out.append('서로 다른 조 %d' % len(arts))
    return '\n'.join(out)


