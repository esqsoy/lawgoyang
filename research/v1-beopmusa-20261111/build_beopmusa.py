def add(y, p, q, sub, law, art, para, basis, conf, issue, cur=None):
    if law in NOT_IN_SOURCES:
        conf = 'U'
    r = {
        'year': y, 'round': y - 1994, 'part': PART[p], 'q': q, 'sub': sub,
        'law': LAW.get(law, law), 'article': art, 'para': para,
        'basis': BASIS[basis], 'confidence': CONF[conf], 'issue': issue,
        'kind': KIND.get(law, '법률'),
    }
    if cur is not None:
        r['current'] = cur
    rows.append(r)


def b(y, p, q, sub, name, issue, basis='C', conf=None, cur=None):
    for law, art, para, c in BUNDLE[name]:
        BUNDLE_ROWS.append([len(rows), name])
        add(y, p, q, sub, law, art, para, basis, conf or c, issue, cur)


def s(y, p, q, sub, qtype='사례', pts=''):
    subqs.append({'year': y, 'round': y - 1994, 'part': PART[p], 'q': q, 'sub': sub,
                  'qtype': qtype, 'points': pts})


