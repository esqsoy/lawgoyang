def add(y, q, sub, law, art, para, basis, conf, issue, cur=None):
    r = {
        'year': y, 'round': y - 1963, 'part': PART, 'q': q, 'sub': sub,
        'law': LAW.get(law, law), 'article': art, 'para': para,
        'basis': BASIS[basis], 'confidence': CONF[conf], 'issue': issue,
        'kind': KIND.get(law, '법률'),
    }
    if cur is not None:
        r['current'] = cur
    rows.append(r)


def b(y, q, sub, name, issue, basis='C', conf=None, cur=None):
    for law, art, para, c in BUNDLE[name]:
        BUNDLE_ROWS.append([len(rows), name])
        add(y, q, sub, law, art, para, basis, conf or c, issue, cur)


